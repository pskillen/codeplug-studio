/**
 * AT-D890UV tune unit: the loaded bytes that are not one of the first-class scalars or tables in
 * `calibration.ts`. Every row is a V1.05 static trace (radio repo PR #245, ledger F349-F356); nothing is
 * validated on hardware. "Factory label" is the vendor's factory-mode name for the item (table 0x0818E0E0).
 * Confidence: `traced` is code-traced use and meaning; `partially-traced` is traced use with an inferred
 * meaning (marked "inferred" in the meaning text). Bytes nothing reads are `no-reader` or `defaults-only`.
 */

export type AtD890CalFieldKind = 'field' | 'no-reader' | 'defaults-only';
export type AtD890CalFieldOrder = 'single-byte' | 'little-endian' | 'big-endian' | 'bytes';

export interface AtD890CalFieldDef {
  id: string;
  label: string;
  offset: number;
  length: number;
  kind: AtD890CalFieldKind;
  /** Word layout: 'big-endian' applies to every 16-bit word of the field. */
  byteOrder: AtD890CalFieldOrder;
  encoding: string;
  /** Vendor factory-mode name (secondary name), with the factory item number. */
  factoryLabel?: string;
  meaning: string;
  unit: string;
  inferred: boolean;
  /** Firmware consumer addresses or ledger ids. */
  evidence: string;
}

